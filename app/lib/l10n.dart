/// Translate [key] into the current language, filling {placeholders} from [args].
String tr(String key, [Map<String, Object> args = const {}]) {
  var s = _strings[settings.lang]?[key] ?? _strings['en']![key] ?? key;
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

String depthText(String depth) =>
    tr(const {'ankle', 'knee', 'waist', 'above_waist'}.contains(depth) ? depth : 'shallow');

String ageText(int minutes) {
  if (minutes < 1) return tr('justNow');
  if (minutes < 60) return tr('minAgo', {'n': minutes});
  return tr('hAgo', {'n': minutes ~/ 60});
}

String km(int? metres) => ((metres ?? 0) / 1000).toStringAsFixed(1);
